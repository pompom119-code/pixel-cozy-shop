export function createInitialSaveState(themeId: ShopThemeId, customName?: string): ShopSaveState {
  const theme = SHOP_THEMES[themeId];
  const starterRecipes = theme.recipes.filter((r) => r.isStarter).map((r) => r.id);
  const initialInventory: Record<string, number> = {};
  theme.ingredients.forEach((ing, idx) => {
    initialInventory[ing.id] = ing.isRare ? 2 : idx < 4 ? 6 : 4;
  });

  const initialLevels: Record<string, number> = {};
  starterRecipes.forEach((id) => {
    initialLevels[id] = 1;
  });

  // Note: Row 0 (gy=0, gx=1..8) is reserved for the 8 Ingredient Crates!
  // Rows 1..3 are kitchen work zone; Rows 4..6 are cozy customer dining zone!
  return {
    themeId,
    shopName: (customName && customName.trim()) || theme.defaultShopName,
    gold: 420,
    reputation: 15,
    day: 1,
    minuteOfDay: 540,
    expansionLevel: 1,
    placedFurniture: [
      // Kitchen Prep & Cooking Stations (Row 2)
      { uid: 'init_board_1', itemId: 'prep_board', gx: 1, gy: 2 },
      { uid: 'init_board_2', itemId: 'prep_board', gx: 2, gy: 2 },
      { uid: 'init_stove_1', itemId: 'craft_stove', gx: 4, gy: 2 },
      { uid: 'init_stove_2', itemId: 'craft_stove', gx: 5, gy: 2 },
      { uid: 'init_counter_1', itemId: 'work_counter', gx: 6, gy: 2 },
      { uid: 'init_plates_1', itemId: 'plate_rack', gx: 7, gy: 2 },
      { uid: 'init_sink_1', itemId: 'wash_sink', gx: 8, gy: 2 },
      { uid: 'init_trash_1', itemId: 'trash_bin', gx: 9, gy: 1 },
      // Customer Dining Tables (Row 5)
      { uid: 'init_table_1', itemId: 'wood_table_2', gx: 2, gy: 5 },
      { uid: 'init_table_2', itemId: 'wood_table_2', gx: 5, gy: 5 },
      { uid: 'init_table_3', itemId: 'wood_table_2', gx: 8, gy: 5 },
      { uid: 'init_plant_1', itemId: 'sunny_plant', gx: 9, gy: 4 },
    ],
    inventory: initialInventory,
    unlockedRecipes: starterRecipes,
    recipeLevels: initialLevels,
    featuredRecipeId: starterRecipes[0],
    triedCombos: [],
    revealedHints: [],
    hiredStaffLevels: {},
    regularPoints: {},
    unlockedChapters: {},
    totalServed: 0,
    todayEarned: 0,
    todayServed: 0,
    todayRegularVisits: 0,
  };
}
